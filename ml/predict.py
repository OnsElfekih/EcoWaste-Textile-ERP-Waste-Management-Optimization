"""Command-line smoke test, using exactly the artifact consumed by Odoo."""
from pathlib import Path
import joblib
import pandas as pd

path = Path(__file__).resolve().parent.parent / 'ecowaste_textile' / 'ml_artifacts' / 'model.joblib'
if not path.is_file():
    raise SystemExit('First run: python ml/generate_dataset.py && python ml/train.py')
artifact = joblib.load(path)  # Only load artifacts generated by your own training script.
row = {'textile_material': 'cotton', 'waste_origin': 'cutting',
       'waste_cause': 'offcut', 'textile_quality': 'good',
       'scrap_size': 'large', 'textile_condition': 'clean', 'hazard_level': 'low'}
frame = pd.DataFrame([row], columns=artifact['features'])
pipe = artifact['pipeline']
pred = pipe.predict(frame)[0]
classes = list(pipe.classes_)
probs = pipe.predict_proba(frame)[0]
print('Features:', row)
print('Prediction:', pred)
print('Confidence estimate:', round(float(max(probs)), 4))
print('Probabilities:', dict(zip(classes, [round(float(p), 4) for p in probs])))
